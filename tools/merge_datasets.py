"""
tools/merge_datasets.py — Hợp Nhất & Chuẩn Hóa Dataset Cho YOLOv11 (RoadGuard AI)
==================================================================================
Tích hợp:
  1. archive.zip: 3,940 ảnh khuyết tật ổ gà gán nhãn Bounding Box (Train, Valid, Test).
  2. surface-crack-detection.zip: Trích xuất các mẫu âm tính (Negative/Background samples)
     chuẩn theo khuyến nghị của Ultralytics (5-10% tập train) để triệt tiêu lỗi nhận nhầm bánh xe/mặt đường sạch.
  3. Xuất thư mục hoàn chỉnh data/unified_dataset và đóng gói unified_road_dataset.zip
     để kéo thả trực tiếp lên Google Colab.
"""

import os
import sys
import glob
import shutil
import zipfile
from pathlib import Path
from typing import Optional

# Hỗ trợ hiển thị tiếng Việt và emoji trên Windows console
if sys.platform.startswith("win"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass


def merge_datasets(
    pothole_zip_path: str = r"F:\Fake_admin\Downloads\tổng hợp thông tin\archive.zip",
    crack_zip_path: str = r"F:\Fake_admin\Downloads\tổng hợp thông tin\surface-crack-detection.zip",
    output_dir: str = r"F:\train AI đồ án\data\unified_dataset",
    output_zip_path: str = r"F:\Fake_admin\Downloads\tổng hợp thông tin\unified_road_dataset.zip",
    num_negative_samples: int = 400
):
    pothole_zip = Path(pothole_zip_path)
    crack_zip = Path(crack_zip_path)
    out_path = Path(output_dir)
    out_zip = Path(output_zip_path)

    print("=" * 70)
    print("🚀 TIẾN TRÌNH HỢP NHẤT & CHUẨN HÓA DATASET ROADGUARD AI")
    print(f"📦 Nguồn 1 (Ổ gà - Bounding Box): {pothole_zip}")
    print(f"📦 Nguồn 2 (Mẫu âm tính - Negative): {crack_zip}")
    print(f"📁 Thư mục xuất xưởng: {out_path}")
    print("=" * 70)

    if not pothole_zip.exists():
        raise FileNotFoundError(f"Không tìm thấy file: {pothole_zip}")
    if not crack_zip.exists():
        raise FileNotFoundError(f"Không tìm thấy file: {crack_zip}")

    # Làm sạch thư mục đích nếu đã có
    if out_path.exists():
        print(f"🧹 Đang làm sạch thư mục cũ: {out_path}...")
        shutil.rmtree(out_path)
    out_path.mkdir(parents=True, exist_ok=True)

    # 1. Giải nén tập Pothole (archive.zip)
    print("\n[Bước 1/4] Đang giải nén tập dữ liệu Pothole (archive.zip)...")
    with zipfile.ZipFile(pothole_zip, 'r') as z:
        z.extractall(out_path)
    print("   ✅ Giải nén Pothole thành công.")

    # 2. Trích xuất Mẫu Âm Tính (Negative Samples) từ surface-crack-detection.zip
    print(f"\n[Bước 2/4] Đang trích xuất {num_negative_samples} mẫu âm tính (Negative Samples)...")
    train_neg_count = int(num_negative_samples * 0.80)   # 80% train = 320
    val_neg_count = int(num_negative_samples * 0.15)     # 15% valid = 60
    test_neg_count = num_negative_samples - train_neg_count - val_neg_count # 5% test = 20

    splits = [
        ("train", train_neg_count),
        ("valid", val_neg_count),
        ("test", test_neg_count)
    ]

    with zipfile.ZipFile(crack_zip, 'r') as z:
        # Lấy danh sách tất cả các ảnh trong thư mục Negative/
        neg_files = [f for f in z.namelist() if f.startswith("Negative/") and f.lower().endswith((".jpg", ".png", ".jpeg"))]
        neg_files.sort()
        print(f"   ℹ️ Tổng số ảnh Negative tìm thấy trong zip: {len(neg_files)} ảnh.")

        idx = 0
        for split_name, count in splits:
            img_dir = out_path / split_name / "images"
            lbl_dir = out_path / split_name / "labels"
            img_dir.mkdir(parents=True, exist_ok=True)
            lbl_dir.mkdir(parents=True, exist_ok=True)

            print(f"   📥 Đang nạp {count} ảnh âm tính vào '{split_name}'...")
            for i in range(count):
                if idx >= len(neg_files):
                    break
                src_filename = neg_files[idx]
                idx += 1

                # Đặt tên mới có tiền tố neg_ để tránh trùng lặp
                clean_name = f"neg_concrete_{idx:05d}.jpg"
                clean_label = f"neg_concrete_{idx:05d}.txt"

                target_img_path = img_dir / clean_name
                target_lbl_path = lbl_dir / clean_label

                # Trích xuất ảnh
                with z.open(src_filename) as src_file, open(target_img_path, "wb") as dst_file:
                    dst_file.write(src_file.read())

                # Tạo file nhãn rỗng (0 bytes) theo chuẩn Ultralytics YOLO
                with open(target_lbl_path, "w", encoding="utf-8") as f:
                    pass

    print(f"   ✅ Đã nạp thành công {num_negative_samples} mẫu âm tính kèm file nhãn rỗng.")

    # 3. Tạo file cấu hình data.yaml chuẩn hóa
    print("\n[Bước 3/4] Tạo cấu hình chuẩn hóa data.yaml...")
    yaml_content = """# RoadGuard AI — Unified Dataset (Pothole + Negative Background Samples)
# Auto-generated by tools/merge_datasets.py

train: train/images
val: valid/images
test: test/images

nc: 1
names: ['pothole']
"""
    yaml_path = out_path / "data.yaml"
    with open(yaml_path, "w", encoding="utf-8") as f:
        f.write(yaml_content)
    print(f"   ✅ Đã ghi cấu hình tại: {yaml_path}")

    # Kiểm kê số lượng file
    train_imgs = len(list((out_path / "train" / "images").glob("*.*")))
    val_imgs = len(list((out_path / "valid" / "images").glob("*.*")))
    test_imgs = len(list((out_path / "test" / "images").glob("*.*")))
    total_imgs = train_imgs + val_imgs + test_imgs

    print("\n📊 BẢNG TỔNG KẾT DATASET ĐÃ HỢP NHẤT:")
    print(f"   - Tập Train: {train_imgs} ảnh (Gồm 3,345 ảnh ổ gà + {train_neg_count} mẫu âm tính)")
    print(f"   - Tập Valid: {val_imgs} ảnh (Gồm 397 ảnh ổ gà + {val_neg_count} mẫu âm tính)")
    print(f"   - Tập Test:  {test_imgs} ảnh (Gồm 198 ảnh ổ gà + {test_neg_count} mẫu âm tính)")
    print(f"   - TỔNG CỘNG: {total_imgs} ảnh hoàn thiện 100%!")

    # 4. Đóng gói file zip hoàn chỉnh để sẵn sàng kéo thả lên Colab
    print(f"\n[Bước 4/4] Đang đóng gói tệp zip tải lên Colab: {out_zip}...")
    out_zip.parent.mkdir(parents=True, exist_ok=True)
    if out_zip.exists():
        out_zip.unlink()

    with zipfile.ZipFile(out_zip, 'w', zipfile.ZIP_DEFLATED) as z:
        for root, dirs, files in os.walk(out_path):
            for file in files:
                full_path = Path(root) / file
                rel_path = full_path.relative_to(out_path)
                z.write(full_path, arcname=str(rel_path))

    zip_size_mb = out_zip.stat().st_size / (1024 * 1024)
    print(f"   🎉 Đóng gói thành công: {out_zip} ({zip_size_mb:.2f} MB)")
    print("=" * 70)
    print("🚀 HOÀN THÀNH TOÀN BỘ TIẾN TRÌNH HỢP NHẤT DATASET!")
    print("=" * 70)


if __name__ == "__main__":
    merge_datasets()
